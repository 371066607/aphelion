#!/usr/bin/env python3
"""Validate and embed the prepared RGBA environment atlas without extra dependencies."""
import base64
import struct
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
source=ROOT/'assets/environment/environment-atlas.png'
raw=source.read_bytes()
if raw[:8]!=b'\x89PNG\r\n\x1a\n' or raw[12:16]!=b'IHDR' or len(raw)<33:raise ValueError('Environment atlas must be PNG')
width,height,depth,color=struct.unpack('>IIBB',raw[16:26])
if (width,height,depth,color)!=(1024,768,8,6):raise ValueError('Environment atlas must be prepared 1024x768 RGBA')
frames={name:entry['packed'] for name,entry in json.loads((ROOT/'assets/environment/environment-bounds.json').read_text()).items()}
if len(frames)!=12 or any(len(b)!=4 or min(b)<0 or b[2]<=0 or b[3]<=0 or b[0]+b[2]>width or b[1]+b[3]>height for b in frames.values()):raise ValueError('Invalid measured environment frames')
(ROOT/'src/environment_art_data.js').write_text('// Generated by assets/build_environment.py; do not edit.\nwindow.APH=window.APH||{};APH.ENVIRONMENT_ART_DATA="data:image/png;base64,'+base64.b64encode(raw).decode('ascii')+'";\nAPH.ENVIRONMENT_ART_FRAMES='+json.dumps(frames,separators=(',',':'))+';\n',encoding='utf8')
print(f'Embedded environment atlas: {len(raw)//1024} KB')
